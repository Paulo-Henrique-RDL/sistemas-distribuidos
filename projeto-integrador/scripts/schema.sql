-- =============================================================================
-- Sistema de contas a pagar e a receber - estrutura do banco de dados
-- Banco: H2 (compativel com o dialeto padrao SQL)
-- =============================================================================
--
-- Em execucao normal a aplicacao NAO usa este script: o Hibernate cria e
-- atualiza as tabelas a partir das entidades (spring.jpa.hibernate.ddl-auto=update).
--
-- Este arquivo existe por duas razoes:
--   1. a entrega exige os scripts de criacao e configuracao do banco;
--   2. ele documenta, em SQL, a estrutura que as entidades geram, servindo de
--      referencia para quem for criar o banco em outro SGBD.
--
-- Para usar este script no lugar da criacao automatica, troque no
-- application.properties:  spring.jpa.hibernate.ddl-auto=validate
-- =============================================================================

DROP TABLE IF EXISTS conta_receber;
DROP TABLE IF EXISTS conta_pagar;
DROP TABLE IF EXISTS forma_pagamento;
DROP TABLE IF EXISTS categoria;
DROP TABLE IF EXISTS pessoa;

-- -----------------------------------------------------------------------------
-- Pessoa: cliente, fornecedor ou os dois papeis.
-- O documento (CPF ou CNPJ) e unico e identifica a pessoa no sistema.
-- -----------------------------------------------------------------------------
CREATE TABLE pessoa (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    documento  VARCHAR(20)  NOT NULL,
    tipo       VARCHAR(20)  NOT NULL,
    email      VARCHAR(120),
    telefone   VARCHAR(20),
    CONSTRAINT uk_pessoa_documento UNIQUE (documento),
    CONSTRAINT ck_pessoa_tipo CHECK (tipo IN ('CLIENTE', 'FORNECEDOR', 'AMBOS'))
);

-- -----------------------------------------------------------------------------
-- Categoria financeira das contas.
-- -----------------------------------------------------------------------------
CREATE TABLE categoria (
    id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(80)  NOT NULL,
    descricao VARCHAR(200),
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

-- -----------------------------------------------------------------------------
-- Forma usada na quitacao. A mesma tabela atende contas a pagar e a receber.
-- -----------------------------------------------------------------------------
CREATE TABLE forma_pagamento (
    id   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    CONSTRAINT uk_forma_pagamento_nome UNIQUE (nome)
);

-- -----------------------------------------------------------------------------
-- Conta a pagar: obrigacao com um fornecedor.
--
-- NUMERIC(15,2) e nao FLOAT: valores monetarios exigem precisao exata, e o
-- ponto flutuante acumula erro de arredondamento nas somas de relatorio.
--
-- A situacao VENCIDA nao aparece no CHECK porque nunca e gravada: a conta fica
-- ABERTA e a aplicacao deriva a situacao comparando o vencimento com a data atual.
-- -----------------------------------------------------------------------------
CREATE TABLE conta_pagar (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao          VARCHAR(200)  NOT NULL,
    numero_documento   VARCHAR(40),
    fornecedor_id      BIGINT        NOT NULL,
    categoria_id       BIGINT        NOT NULL,
    valor              NUMERIC(15,2) NOT NULL,
    data_emissao       DATE          NOT NULL,
    data_vencimento    DATE          NOT NULL,
    data_pagamento     DATE,
    valor_pago         NUMERIC(15,2),
    forma_pagamento_id BIGINT,
    situacao           VARCHAR(20)   NOT NULL,
    observacao         VARCHAR(500),
    data_cadastro      TIMESTAMP     NOT NULL,
    data_atualizacao   TIMESTAMP,
    CONSTRAINT fk_conta_pagar_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES pessoa (id),
    CONSTRAINT fk_conta_pagar_categoria  FOREIGN KEY (categoria_id)  REFERENCES categoria (id),
    CONSTRAINT fk_conta_pagar_forma      FOREIGN KEY (forma_pagamento_id) REFERENCES forma_pagamento (id),
    CONSTRAINT ck_conta_pagar_situacao CHECK (situacao IN ('ABERTA', 'PAGA', 'CANCELADA')),
    CONSTRAINT ck_conta_pagar_valor    CHECK (valor > 0),
    CONSTRAINT ck_conta_pagar_datas    CHECK (data_vencimento >= data_emissao)
);

-- -----------------------------------------------------------------------------
-- Conta a receber: direito sobre um cliente.
-- Espelha a conta a pagar, trocando fornecedor por cliente e pagamento por
-- recebimento. Tabelas separadas de proposito: na segunda etapa do projeto cada
-- uma vira um microsservico com banco proprio, e o corte nao exige dividir dados.
-- -----------------------------------------------------------------------------
CREATE TABLE conta_receber (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao            VARCHAR(200)  NOT NULL,
    numero_documento     VARCHAR(40),
    cliente_id           BIGINT        NOT NULL,
    categoria_id         BIGINT        NOT NULL,
    valor                NUMERIC(15,2) NOT NULL,
    data_emissao         DATE          NOT NULL,
    data_vencimento      DATE          NOT NULL,
    data_recebimento     DATE,
    valor_recebido       NUMERIC(15,2),
    forma_recebimento_id BIGINT,
    situacao             VARCHAR(20)   NOT NULL,
    observacao           VARCHAR(500),
    data_cadastro        TIMESTAMP     NOT NULL,
    data_atualizacao     TIMESTAMP,
    CONSTRAINT fk_conta_receber_cliente   FOREIGN KEY (cliente_id)   REFERENCES pessoa (id),
    CONSTRAINT fk_conta_receber_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT fk_conta_receber_forma     FOREIGN KEY (forma_recebimento_id) REFERENCES forma_pagamento (id),
    CONSTRAINT ck_conta_receber_situacao CHECK (situacao IN ('ABERTA', 'RECEBIDA', 'CANCELADA')),
    CONSTRAINT ck_conta_receber_valor    CHECK (valor > 0),
    CONSTRAINT ck_conta_receber_datas    CHECK (data_vencimento >= data_emissao)
);

-- -----------------------------------------------------------------------------
-- Indices das colunas mais usadas nos filtros exigidos pelo enunciado
-- (consultas por periodo e por situacao).
-- -----------------------------------------------------------------------------
CREATE INDEX idx_conta_pagar_vencimento   ON conta_pagar   (data_vencimento);
CREATE INDEX idx_conta_pagar_situacao     ON conta_pagar   (situacao);
CREATE INDEX idx_conta_receber_vencimento ON conta_receber (data_vencimento);
CREATE INDEX idx_conta_receber_situacao   ON conta_receber (situacao);
